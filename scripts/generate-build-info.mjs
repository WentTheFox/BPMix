#!/usr/bin/env node
// Regenerates packages/core/src/buildInfo.ts with the current commit hash
// and timestamp. Run automatically (pre* npm-lifecycle hooks) before
// apps/web and apps/mobile's dev/build/start scripts, and once via the
// workspace root's postinstall - see those package.json files. The output
// is committed rather than gitignored, so a fresh clone (or any tsc
// invocation that bypasses those hooks entirely) always has a real file to
// import; expect it to show as locally modified after running any of the
// above, which is fine to leave uncommitted.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(dirname, '../packages/core/src/buildInfo.ts');

function gitShortCommit() {
  // The Docker build context excludes .git entirely (see .dockerignore) -
  // docker-publish.yml passes the real commit in as this build arg/env var
  // instead, since `git rev-parse` has nothing to read in that environment.
  if (process.env.GIT_COMMIT_OVERRIDE) return process.env.GIT_COMMIT_OVERRIDE.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { cwd: dirname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

const commit = gitShortCommit();
const buildTime = new Date().toISOString();

writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-build-info.mjs - do not edit by hand.
// Regenerated before every dev/build/start (see apps/web and apps/mobile's
// package.json pre* hooks) - a locally modified diff here after running
// one of those is expected, not a stray edit to revert.
export const BUILD_COMMIT = ${JSON.stringify(commit)};
export const BUILD_TIME = ${JSON.stringify(buildTime)};
`,
);
