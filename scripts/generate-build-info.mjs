#!/usr/bin/env node
// Regenerates packages/core/src/buildInfo.ts with the current commit hash,
// version, and timestamp. Run automatically (pre* npm-lifecycle hooks)
// before apps/web and apps/mobile's dev/build/start/typecheck scripts -
// see those package.json files. The output is committed rather than
// gitignored, so a fresh clone (or any tsc invocation that bypasses those
// hooks entirely) always has a real file to import; expect it to show as
// locally modified after running any of the above, which is fine to leave
// uncommitted.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(dirname, '../packages/core/src/buildInfo.ts');

// The Docker build context excludes .git entirely (see .dockerignore), and
// a plain `git describe`/`rev-parse` on a shallow CI checkout may not see
// tag history either - docker-publish.yml and native-builds.yml pass the
// real commit/version in as these build args/env vars instead of relying
// on git being able to answer either question in every environment this
// runs in.
function gitShortCommit() {
  if (process.env.GIT_COMMIT_OVERRIDE) return process.env.GIT_COMMIT_OVERRIDE.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { cwd: dirname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

/** A version tag (e.g. "v1.2.3" - native-builds.yml only creates a GitHub Release, and thus a tag, on a "v*" push) if built from one, else the nearest tag plus a distance/hash suffix, else just the short commit. */
function gitVersion() {
  if (process.env.GIT_VERSION_OVERRIDE) return process.env.GIT_VERSION_OVERRIDE;
  try {
    return execSync('git describe --tags --always', { cwd: dirname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

const commit = gitShortCommit();
const version = gitVersion();
const buildTime = new Date().toISOString();

writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-build-info.mjs - do not edit by hand.
// Regenerated before every dev/build/start/typecheck (see apps/web and
// apps/mobile's package.json pre* hooks) - a locally modified diff here
// after running one of those is expected, not a stray edit to revert.
export const BUILD_COMMIT = ${JSON.stringify(commit)};
export const BUILD_VERSION = ${JSON.stringify(version)};
export const BUILD_TIME = ${JSON.stringify(buildTime)};
`,
);
