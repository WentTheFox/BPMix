#!/usr/bin/env node
// Regenerates packages/core/src/buildInfo.ts with the current commit hash,
// version, and timestamp. The output is gitignored (previously it was
// committed instead, which meant it permanently showed as locally modified
// after running any command that regenerates it, and the committed
// "baseline" was never actually accurate - CI regenerates it fresh for
// every build too and never commits the result back, so a stale committed
// copy served no real purpose). Run automatically via the root
// package.json's postinstall (so a fresh clone/install always has the file
// before anyone opens an editor or runs a bare `tsc`), and again via each
// app's own pre* npm-lifecycle hooks (dev/build/start/typecheck - see those
// package.json files) and packages/core's own pretypecheck/pretest, so it
// stays current right before whatever actually needs it.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(dirname, '../packages/core/src/buildInfo.ts');
// The root postinstall hook runs this against the Docker build's
// manifests-only install layer (see Dockerfile), which copies
// packages/core/package.json but not its src/ directory - mkdir first so
// that layer doesn't fail with ENOENT before the real `COPY . .` (and
// apps/web's own prebuild, which regenerates this correctly with real
// commit/version info) ever runs. A no-op once src/ already exists.
mkdirSync(path.dirname(outPath), { recursive: true });

// The Docker build context excludes .git entirely (see .dockerignore), and
// a plain `git describe`/`rev-parse` on a shallow CI checkout may not see
// tag history either - docker-publish.yml and native-builds.yml pass the
// real commit/version in as these build args/env vars instead of relying
// on git being able to answer either question in every environment this
// runs in.
function gitShortCommit() {
  if (process.env.GIT_COMMIT_OVERRIDE) return process.env.GIT_COMMIT_OVERRIDE.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { cwd: dirname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

/** A version tag (e.g. "v1.2.3" - native-builds.yml only creates a GitHub Release, and thus a tag, on a "v*" push) if built from one, else the nearest tag plus a distance/hash suffix, else just the short commit. */
function gitVersion() {
  if (process.env.GIT_VERSION_OVERRIDE) return process.env.GIT_VERSION_OVERRIDE;
  try {
    return execSync('git describe --tags --always', { cwd: dirname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

const commit = gitShortCommit();
const version = gitVersion();
const buildTime = new Date().toISOString();

writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-build-info.mjs - do not edit by hand.
// Gitignored and regenerated before every install/dev/build/start/typecheck
// (see the root and each app's package.json pre*/postinstall hooks) - never
// commit this file.
export const BUILD_COMMIT = ${JSON.stringify(commit)};
export const BUILD_VERSION = ${JSON.stringify(version)};
export const BUILD_TIME = ${JSON.stringify(buildTime)};
`,
);
